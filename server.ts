function cleanAgentResponse(text: string): string {
  // 1. Remove <think>...</think> blocks (case-insensitive)
  let cleaned = text.replace(/<think>[\s\S]*?<\/think>/gi, '');
  
  // 2. Remove common analytical headers often generated by the model's self-reasoning
  // Matches "Pemikiran Analitis", "Thinking Phase", etc. and everything until a major separator or the end
  cleaned = cleaned.replace(/(Pemikiran Analitis|Thinking Phase|Real-Time Thinking|Proses Berpikir)[\s\S]*?(?=---|$)/gi, '');
  
  // 3. Remove horizontal separators that might be left over at the start or end
  cleaned = cleaned.replace(/^[\s\n-]{3,}/g, '').replace(/[\s\n-]{3,}$/g, '');
  
  return cleaned.trim();
}

async function callChatCompletionStream(
  res: express.Response,
  messages: any[],
  requestedModel: string,
  apiKey: string,
  isThinkingMode: boolean
): Promise<string> {
  const modelsToTry = Array.from(new Set([
    requestedModel || 'auto',
    ...DEFAULT_FALLBACK_MODELS
  ]));

  const openai = new OpenAI({
    apiKey: apiKey || 'dummy',
    baseURL: 'https://api.hcnsec.cn/v1'
  });

  const formattedMessages = JSON.parse(JSON.stringify(messages));
  if (isThinkingMode) {
    const sysMsgIndex = formattedMessages.findIndex((m: any) => m.role === 'system');
    const thinkingInstruction = '\n\n[Mode Berpikir Real-Time]\nAnalisis pertanyaan secara mendalam dan terstruktur. Sebelum memberikan jawaban akhir, tampilkan pemikiran analisis selangkah demi selangkah secara rinci dan transparan.';
    if (sysMsgIndex !== -1) {
      formattedMessages[sysMsgIndex].content += thinkingInstruction;
    } else {
      formattedMessages.unshift({ role: 'system', content: thinkingInstruction });
    }
  }

  let fullText = '';
  let streamWorked = false;

  for (const model of modelsToTry) {
    try {
      const stream = await openai.chat.completions.create({
        model,
        messages: formattedMessages,
        stream: true,
      });

      let inReasoning = false;

      for await (const chunk of stream) {
        const delta = chunk.choices[0]?.delta as any;
        const reasoningDelta = delta?.reasoning_content || delta?.reasoning;
        const contentDelta = delta?.content || '';

        if (reasoningDelta) {
          if (!inReasoning) {
            inReasoning = true;
            const startTag = '<think>\n';
            fullText += startTag;
            res.write(`data: ${JSON.stringify({ chunk: startTag })}\n\n`);
          }
          fullText += reasoningDelta;
          res.write(`data: ${JSON.stringify({ chunk: reasoningDelta })}\n\n`);
        } else {
          if (inReasoning && contentDelta) {
            inReasoning = false;
            const endTag = '\n</think>\n\n';
            fullText += endTag;
            res.write(`data: ${JSON.stringify({ chunk: endTag })}\n\n`);
          }
          if (contentDelta) {
            fullText += contentDelta;
            res.write(`data: ${JSON.stringify({ chunk: contentDelta })}\n\n`);
          }
        }
      }

      if (inReasoning) {
        const endTag = '\n</think>\n\n';
        fullText += endTag;
        res.write(`data: ${JSON.stringify({ chunk: endTag })}\n\n`);
      }

      streamWorked = true;
      break;
    } catch (err: any) {
      console.warn(`[Stream Error Model ${model}]`, err?.message || err);
    }
  }

  if (!streamWorked) {
    try {
      const nonStreamText = await callChatCompletion(formattedMessages, requestedModel, apiKey);
      fullText = nonStreamText;
      const chunkSize = 15;
      for (let i = 0; i < nonStreamText.length; i += chunkSize) {
        const chunk = nonStreamText.slice(i, i + chunkSize);
        res.write(`data: ${JSON.stringify({ chunk })}\n\n`);
      }
      streamWorked = true;
    } catch (err: any) {
      res.write(`data: ${JSON.stringify({ error: err?.message || 'Gagal menghasilkan respons' })}\n\n`);
    }
  }

  return fullText;
}

async function callChatCompletion(messages: any[], requestedModel: string, apiKey: string) {
  const modelsToTry = Array.from(new Set([
    requestedModel || 'auto',
    ...DEFAULT_FALLBACK_MODELS
  ]));

  const openai = new OpenAI({
    apiKey: apiKey || 'dummy',
    baseURL: 'https://api.hcnsec.cn/v1'
  });

  let lastError: any = null;

  for (const model of modelsToTry) {
    try {
      const response = await openai.chat.completions.create({
        model,
        messages,
      });
      const content = response.choices[0]?.message?.content;
      if (content) {
        return content;
      }
    } catch (err: any) {
      console.warn(`[API Failure] Model ${model} failed:`, err?.message || err);
      lastError = err;
    }
  }

  // Fallback to Google Gemini API if GEMINI_API_KEY is available
  if (process.env.GEMINI_API_KEY) {
    try {
      console.log('[API Fallback] Attempting Gemini API fallback...');
      const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
      let systemInstruction = '';
      const contents: Array<{ role: string; parts: Array<{ text: string }> }> = [];

      for (const m of messages) {
        if (m.role === 'system') {
          systemInstruction += (systemInstruction ? '\n\n' : '') + m.content;
        } else {
          contents.push({
            role: m.role === 'assistant' ? 'model' : 'user',
            parts: [{ text: m.content || '' }]
          });
        }
      }

      const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: contents.length > 0 ? contents : [{ role: 'user', parts: [{ text: 'Halo' }] }],
        config: systemInstruction ? { systemInstruction } : undefined,
      });

      if (response.text) {
        return response.text;
      }
    } catch (geminiErr: any) {
      console.error('[Gemini API Fallback Error]', geminiErr);
    }
  }

  throw lastError || new Error('Layanan AI sedang tidak tersedia, silakan coba lagi beberapa saat.');
}

